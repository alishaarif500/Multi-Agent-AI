"""## Phase 4: Multi-Agent Orchestration Engine

### Subtask:
Implement the shared state database and route control workflows using LangGraph to manage task delegation, feedback iterations, and state transitions safely.

**Reasoning**:
Create the LangGraph multi-agent state management representation, define agent nodes, and construct the compiled StateGraph routing workflow with conditional supervisor logic.
"""

from typing import TypedDict, List, Dict, Any, Literal
from langgraph.graph import StateGraph, START, END

# ==========================================
# 1. STATE REPRESENTATION
# ==========================================
class AgentState(TypedDict):
    original_query: str
    execution_history: str
    current_instruction: str
    last_agent_output: str
    reviewer_feedback: str
    next_step: str
    iteration_count: int

# Instantiate the actual agents with the global client
global_client = genai.Client()

supervisor_agent = SupervisorAgent(client=global_client)
research_agent = BaseAgent("Research", RESEARCH_SYSTEM, client=global_client)
analyst_agent = BaseAgent("Data Analyst", ANALYST_SYSTEM, client=global_client)
coding_agent = BaseAgent("Coding", CODING_SYSTEM, client=global_client)
reviewer_agent = CriticalReviewerAgent(client=global_client)
report_agent = BaseAgent("Final Report", REPORT_SYSTEM, client=global_client)

# ==========================================
# 2. AGENT NODE FUNCTIONS
# ==========================================
def supervisor_node(state: AgentState) -> Dict[str, Any]:
    # The supervisor decides the next agent and instructions based on the current state
    try:
        decision = supervisor_agent.route(
            user_query=state["original_query"],
            history=state["execution_history"]
        )
        next_step = decision.next_agent
        instruction = decision.task_instruction
        reasoning = decision.reasoning
    except Exception as e:
        print(f"[Supervisor Error - Fallback triggered]: {e}")
        # Resilient fallback routing logic
        if "Report" not in state["execution_history"] and state["iteration_count"] >= 3:
            next_step = "Final Report"
            instruction = "Summarize the available analytical insights into the final report."
        else:
            next_step = "Coding"
            instruction = "Continue with data processing or model development based on prior objectives."
        reasoning = "Fallback rule triggered due to processing exception."

    # Update execution log
    new_history = state["execution_history"] + f"\n[Supervisor Decision]: Routed to {next_step}. Reasoning: {reasoning}\n"

    return {
        "next_step": next_step,
        "current_instruction": instruction,
        "execution_history": new_history,
        "iteration_count": state["iteration_count"] + 1
    }

def research_node(state: AgentState) -> Dict[str, Any]:
    output = research_agent.execute(state["current_instruction"], state["execution_history"])
    new_history = state["execution_history"] + f"\n[Research Agent Output]:\n{output}\n"
    return {
        "last_agent_output": output,
        "execution_history": new_history
    }

def analyst_node(state: AgentState) -> Dict[str, Any]:
    output = analyst_agent.execute(state["current_instruction"], state["execution_history"])
    new_history = state["execution_history"] + f"\n[Data Analyst Output]:\n{output}\n"
    return {
        "last_agent_output": output,
        "execution_history": new_history
    }

def coding_node(state: AgentState) -> Dict[str, Any]:
    output = coding_agent.execute(state["current_instruction"], state["execution_history"])
    new_history = state["execution_history"] + f"\n[Coding Agent Output]:\n{output}\n"
    return {
        "last_agent_output": output,
        "execution_history": new_history
    }

def reviewer_node(state: AgentState) -> Dict[str, Any]:
    try:
        assessment = reviewer_agent.review(state["current_instruction"], state["last_agent_output"])
        is_passed = assessment.is_passed
        feedback = assessment.feedback_or_bugs
    except Exception as e:
        print(f"[Reviewer Error - Fallback triggered]: {e}")
        is_passed = True
        feedback = "No fatal errors detected during fallback evaluation."

    new_history = state["execution_history"] + f"\n[Critical Reviewer Assessment]: Passed={is_passed}. Feedback: {feedback}\n"
    return {
        "reviewer_feedback": feedback,
        "last_agent_output": f"Passed: {is_passed}. Feedback: {feedback}",
        "execution_history": new_history
    }

def report_node(state: AgentState) -> Dict[str, Any]:
    output = report_agent.execute(state["current_instruction"], state["execution_history"])
    new_history = state["execution_history"] + f"\n[Final Report Agent Output]:\n{output}\n"
    return {
        "last_agent_output": output,
        "execution_history": new_history
    }

# ==========================================
# 3. CONDITIONAL ROUTING EDGE FUNCTION
# ==========================================
def route_next(state: AgentState) -> Literal["Research", "Data Analyst", "Coding", "Critical Reviewer", "Final Report", "__end__"]:
    next_step = state["next_step"]
    # Enforce a hard ceiling iteration limit to prevent infinite loops
    if state["iteration_count"] > 8:
        print("\n--- Iteration limit reached. Forcing flow termination to avoid infinite loops --- \n")
        return "__end__"

    if next_step == "FINISH":
        return "__end__"
    return next_step

# ==========================================
# 4. GRAPH CONSTRUCTION & COMPILATION
# ==========================================
workflow = StateGraph(AgentState)

# Add Nodes
workflow.add_node("Supervisor", supervisor_node)
workflow.add_node("Research", research_node)
workflow.add_node("Data Analyst", analyst_node)
workflow.add_node("Coding", coding_node)
workflow.add_node("Critical Reviewer", reviewer_node)
workflow.add_node("Final Report", report_node)

# Add Edges
workflow.add_edge(START, "Supervisor")

# Connect individual specialists back to the Supervisor
workflow.add_edge("Research", "Supervisor")
workflow.add_edge("Data Analyst", "Supervisor")
workflow.add_edge("Coding", "Supervisor")
workflow.add_edge("Critical Reviewer", "Supervisor")
workflow.add_edge("Final Report", "Supervisor")

# Add Supervisor conditional logic
workflow.add_conditional_edges(
    "Supervisor",
    route_next,
    {
        "Research": "Research",
        "Data Analyst": "Data Analyst",
        "Coding": "Coding",
        "Critical Reviewer": "Critical Reviewer",
        "Final Report": "Final Report",
        "__end__": END
    }
)

# Compile the StateGraph into a runnable engine
orchestrator_app = workflow.compile()
print("LangGraph Multi-Agent Orchestration Engine compiled successfully and is ready to run!")

"""## Phase 5: Environment-Safe Execution Tools

### Subtask:
Create functional tools for secure mathematical calculations, file statistics, and Python code execution context, ensuring complete isolation and error feedback.

**Reasoning**:
Create the isolated execution environment and auxiliary evaluation tools with safety features, capturing stdout and stderr cleanly to support self-correction, along with descriptive tests.
"""

import sys
import io
import traceback
import pandas as pd
from typing import Dict, Any

# ==========================================
# 1. SANDBOX PYTHON CODE EXECUTION UTILITY
# ==========================================
def execute_python_sandbox(code_str: str, custom_globals: dict = None) -> Dict[str, Any]:
    """
    Executes arbitrary Python code in a safe, isolated context.
    Captures standard output, standard error, and returns structured traceback feedback if errors occur.
    """
    # Create an isolated local/global execution context
    if custom_globals is None:
        # Pre-import common useful data science packages
        import numpy as np
        import pandas as pd
        import matplotlib.pyplot as plt
        import seaborn as sns
        custom_globals = {
            "np": np,
            "pd": pd,
            "plt": plt,
            "sns": sns
        }

    # Redirect stdout and stderr
    old_stdout = sys.stdout
    old_stderr = sys.stderr
    redirected_stdout = io.StringIO()
    redirected_stderr = io.StringIO()
    sys.stdout = redirected_stdout
    sys.stderr = redirected_stderr

    success = True
    error_msg = ""

    try:
        # Execute the string containing code
        exec(code_str, custom_globals)
    except Exception as e:
        success = False
        # Retrieve detailed traceback information
        exc_type, exc_value, exc_tb = sys.exc_info()
        tb_lines = traceback.format_exception(exc_type, exc_value, exc_tb)
        error_msg = "".join(tb_lines)
    finally:
        # Restore original streams
        sys.stdout = old_stdout
        sys.stderr = old_stderr

    stdout_val = redirected_stdout.getvalue()
    stderr_val = redirected_stderr.getvalue() + error_msg

    return {
        "success": success,
        "stdout": stdout_val,
        "stderr": stderr_val
    }

# ==========================================
# 2. AUXILIARY DATA STATISTICS & COMPUTE TOOLS
# ==========================================
def get_file_statistics(file_path: str) -> Dict[str, Any]:
    """
    Safely extracts basic structural data statistics for the Data Analyst and Coding Agent.
    """
    try:
        if file_path.endswith('.csv'):
            df = pd.read_csv(file_path)
            return {
                "success": True,
                "rows": df.shape[0],
                "columns": list(df.columns),
                "missing_values": df.isnull().sum().to_dict(),
                "summary_statistics": df.describe(include='all').to_dict()
            }
        else:
            return {"success": False, "error": "Unsupported file format. Only CSV statistics are currently supported."}
    except Exception as e:
        return {"success": False, "error": str(e)}

