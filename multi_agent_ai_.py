class BaseAgent:
    def __init__(self, name: str, system_instruction: str, client: Optional[genai.Client] = None):
        self.name = name
        self.system_instruction = system_instruction
        self.client = client or genai.Client()
        self.model_name = 'gemini-2.5-flash'

    def execute(self, prompt: str, history: Optional[str] = None) -> str:
        full_contents = f"History of prior steps:\n{history}\n\nTask instruction:\n{prompt}" if history else prompt
        response = self.client.models.generate_content(
            model=self.model_name,
            contents=full_contents,
            config=types.GenerateContentConfig(
                system_instruction=self.system_instruction,
                temperature=0.2
            )
        )
        return response.text.strip()

class SupervisorAgent(BaseAgent):
    def __init__(self, client: Optional[genai.Client] = None):
        super().__init__("Supervisor", SUPERVISOR_SYSTEM, client)

    def route(self, user_query: str, history: str) -> SupervisorDecision:
        prompt = f"Original User Goal: {user_query}\n\nGlobal Execution History:\n{history}"
        response = self.client.models.generate_content(
            model=self.model_name,
            contents=prompt,
            config=types.GenerateContentConfig(
                system_instruction=self.system_instruction,
                temperature=0.1,
                response_mime_type="application/json",
                response_schema=SupervisorDecision
            )
        )
        return SupervisorDecision.model_validate_json(response.text.strip())

class CriticalReviewerAgent(BaseAgent):
    def __init__(self, client: Optional[genai.Client] = None):
        super().__init__("Critical Reviewer", REVIEWER_SYSTEM, client)

    def review(self, task: str, execution_output: str) -> ReviewAssessment:
        prompt = f"Task performed: {task}\n\nCode or Output generated to review:\n{execution_output}"
        response = self.client.models.generate_content(
            model=self.model_name,
            contents=prompt,
            config=types.GenerateContentConfig(
                system_instruction=self.system_instruction,
                temperature=0.1,
                response_mime_type="application/json",
                response_schema=ReviewAssessment
            )
        )
        return ReviewAssessment.model_validate_json(response.text.strip())

